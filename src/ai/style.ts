const CLICHES: [RegExp, string][] = [
  [/меня зовут/i, "«Меня зовут…» — начинать с себя"],
  [/я\s+(?:—\s+)?(?:опытный|профессиональн[а-яёa-z]+|веб-?)?\s*разработчик/i, "представление «я разработчик»"],
  [/индивидуальн[а-яёa-z]+ подход/i, "«индивидуальный подход»"],
  [/качественно и в срок|в кратчайшие сроки|точно в срок/i, "«качественно и в срок»"],
  [/команда профессионал/i, "«команда профессионалов»"],
  [/(?:повысить|увеличить|улучшить) эффективност/i, "«повысить эффективность»"],
  [/уникальн[а-яёa-z]+ (?:предложени|решени)/i, "«уникальное предложение/решение»"],
  [/(?:буду )?рад(?:а)? (?:сотрудничеств|помочь|предложить)/i, "«буду рад сотрудничеству/помочь»"],
  [/современн[а-яёa-z]+ технологи/i, "«современные технологии»"],
  [/выгодн[а-яёa-z]+ услови/i, "«выгодные условия»"],
  [/широк[а-яёa-z]+ спектр/i, "«широкий спектр»"],
  [/(?:вывести|выведу) (?:ваш )?бизнес на новый уровень|новый уровень/i, "«на новый уровень»"],
  [/цифровизац|цифров[а-яёa-z]+ трансформац/i, "«цифровизация/трансформация»"],
  [/(?:надеюсь|надеемся) на (?:плодотворн|долгосрочн)/i, "«надеюсь на плодотворное сотрудничество»"],
  [/не оставит вас равнодушн/i, "«не оставит равнодушным»"],
  [/с уважением,?\s*$/im, "подпись «С уважением»"],
  [/готов(?:а)? (?:обсудить|ответить на) (?:любые|все) (?:вопросы|детали)/i, "«готов ответить на любые вопросы»"],
  [/(?:более|свыше) \d+ (?:лет|года?) опыт/i, "стаж вместо пользы"],
  [/опыт(?:ом)? работы (?:более|свыше)/i, "стаж вместо пользы"],
  [/(?:ознакомился|изучил) (?:с )?(?:вашим|ваш) (?:заданием|заказом|тз)/i, "«ознакомился с вашим заданием»"],
  [/(?:хочу|хотел(?:а)? бы) предложить (?:вам )?(?:свои|мои) услуги/i, "«хочу предложить свои услуги»"],
];

/** Какие штампы есть в тексте (по одному названию на штамп). В звонке представиться — нормально, поэтому allowIntro. */
export function findCliches(text: string, opts: { allowIntro?: boolean } = {}): string[] {
  const found = new Set<string>();
  for (const [re, label] of CLICHES) {
    if (opts.allowIntro && label.startsWith("«Меня зовут")) continue;
    if (re.test(text)) found.add(label);
  }
  return [...found];
}

