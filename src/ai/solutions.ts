export type RankedSolution = Solution & { signal: boolean };

/**
 * Решения, подходящие этой компании: сначала те, для которых есть сигнал из проверки сайта,
 * внутри — более узкие (специфичные для ниши) выше универсальных.
 */
export function solutionsFor(nicheText: string, check: SiteCheck | null, limit = 5): RankedSolution[] {
  const text = nicheText || "";
  return SOLUTIONS.filter((s) => s.niches.test(text))
    .map((s) => ({ ...s, signal: s.signals ? s.signals(check) : false }))
    .map((s) => ({ s, rank: (s.signal ? 2 : 0) + (s.niches === LOCAL_ANY ? 0 : 1) }))
    .sort((a, b) => b.rank - a.rank)
    .slice(0, limit)
    .map(({ s }) => s);
}

export function findSolution(id: string): Solution | undefined {
  return SOLUTIONS.find((s) => s.id === id);
}

/** Блок для промпта: только подходящие решения, подробно. */
export function solutionsBlock(solutions: RankedSolution[]): string {
  if (!solutions.length) return "";
  return [
    "<solutions>",
    "Решения, которые фрилансер умеет делать и которые подходят этой компании (id — для поля solutionId). Цены и сроки — ориентиры; если в правилах есть свои цены, бери их.",
    ...solutions.map((s) =>
      [
        `### ${s.id}: ${s.title}${s.signal ? " — ЕСТЬ СИГНАЛ из проверки сайта" : ""}`,
        `Боли: ${s.pains.join("; ")}`,
        `Что входит: ${s.deliverables.join("; ")}`,
        `Что даёт: ${s.outcome}`,
        `Цена: ${s.price}; срок: ${s.days}`,
        `Первый шаг без риска: ${s.firstStep}`,
      ].join("\n"),
    ),
    "</solutions>",
  ].join("\n");
}
